CREATE TABLE art_reproductive_health_details (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    visit_id UUID NOT NULL UNIQUE REFERENCES visits(id),
    pregnant BOOLEAN,
    trimester SMALLINT CHECK (trimester BETWEEN 1 AND 3),
    gravida TEXT,
    para TEXT,
    contraception_method VARCHAR(20) CHECK (contraception_method IN ('NONE', 'CONDOM', 'INJECTION', 'PILL', 'OTHER')),
    contraception_other_specify TEXT,
    urethral_discharge BOOLEAN,
    urethral_discharge_comment TEXT,
    vaginal_discharge BOOLEAN,
    vaginal_discharge_comment TEXT,
    genital_ulcers BOOLEAN,
    genital_ulcers_comment TEXT,
    genital_warts BOOLEAN,
    genital_warts_comment TEXT,
    lower_abdominal_pain BOOLEAN,
    lower_abdominal_pain_comment TEXT,
    pap_smear_result TEXT,
    pap_smear_date DATE,
    rpr_date DATE,
    results TEXT,
    specify_treatment_completed TEXT,
    created_by_user_id UUID NOT NULL,
    updated_by_user_id UUID NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL
);
