CREATE TABLE art_initiation_tb_screening (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    visit_id UUID NOT NULL UNIQUE REFERENCES visits(id),
    previous_tb BOOLEAN,
    previous_tb_year INTEGER CHECK (previous_tb_year IS NULL OR previous_tb_year >= 1980),
    previous_tb_extra_pulmonary BOOLEAN,
    previous_tb_pulmonary BOOLEAN,
    current_tb BOOLEAN,
    current_tb_extra_pulmonary BOOLEAN,
    current_tb_pulmonary BOOLEAN,
    current_tb_treatment_start_date DATE,
    symptom_cough_over_two_weeks BOOLEAN,
    symptom_weight_loss BOOLEAN,
    symptom_fever BOOLEAN,
    symptom_night_sweats BOOLEAN,
    symptom_haemoptysis BOOLEAN,
    symptom_fatigue BOOLEAN,
    smear_date_result TEXT,
    culture_sensitivity_date_result DATE,
    clinical_indication TEXT,
    created_by_user_id UUID NOT NULL,
    updated_by_user_id UUID NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
